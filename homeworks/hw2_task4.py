# Мини-блок «рейтинг фильма»

# Безопасный ввод числа с плавающей точкой
while True:
    user_input = input("Введите рейтинг фильма (например, 7.5): ")
    try:
        rating = float(user_input)
        break  # ввод успешен, выходим из цикла
    except ValueError:
        print("Ошибка: нужно ввести именно число (можно с точкой). Попробуйте ещё раз.")

# Тернарный оператор: короткое условие «если-иначе» в одну строку.
# Здесь он уместен, потому что логика простая: всего два варианта verdict
# в зависимости от одного условия (rating >= 7), и нет сложных ветвлений.
verdict = "рекомендуем" if rating >= 7 else "пропустить"

print(f"Рейтинг: {rating}")
print(f"Вердикт: {verdict}")