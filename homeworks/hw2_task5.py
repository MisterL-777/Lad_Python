# Звёздочка: сложные условия и короткое замыкание

# Входные данные (можно заменить на input, если нужно)
login = input("Введите свой логин: ")
password = input("Придумайте пароль: ")
age = int(input("Введите возраст: "))
email = input("Введите email: ")

# Флаги валидности полей
login_ok = bool(login)  # логин не пустой
pass_ok = len(password) >= 6  # пароль не короче 6 символов
age_ok = age >= 18  # совершеннолетний

# Простая проверка email: есть ли '@' и '.' после '@'
# Это упрощённая валидация, но для примера достаточно
email_ok = (
    "@" in email
    and "." in email[email.index("@"):]  # точка есть после собачки
)

# Собираем список ошибок
errors = []

# Проверка логина
if not login_ok:
    errors.append("Логин не может быть пустым.")

# Проверка пароля
if not pass_ok:
    errors.append("Пароль должен быть не короче 6 символов.")

# Проверка возраста
if not age_ok:
    errors.append("Доступ только для пользователей от 18 лет.")

# Проверка email
if not email_ok:
    errors.append("Некорректный email: должен содержать '@' и точку после неё.")

# Итоговое решение: доступ разрешён, если нет ошибок
# Здесь срабатывает короткое замыкание: если errors уже не пустой,
# нам не нужно дальше ничего проверять для решения «доступ запрещён».
if not errors:
    print("Все данные корректны. Доступ разрешён.")
else:
    print("Обнаружены ошибки:")
    for err in errors:
        print("-", err)

# Пример использования and/or/not в одном сложном условии:
# Допустим, мы хотим разрешить доступ только если:
#   - логин валиден И
#   - (пароль валиден И возраст валиден) И
#   - email валиден
#
# can_access = login_ok and (pass_ok and age_ok) and email_ok
#
# Короткое замыкание здесь полезно:
# - Если login_ok == False, Python не станет вычислять остальную часть выражения,
#   потому что результат уже точно False (False and ... = False).
# - Это экономит время и позволяет не делать лишние проверки,
#   например, не проверять email, если логин уже невалиден.