# Сумма введённых чисел до нуля

total = 0  # накапливаем сумму здесь

while True:
    user_input = input("Введите число (0 для завершения): ")
    try:
        num = int(user_input)
    except ValueError:
        print("Ошибка: нужно ввести именно целое число. Попробуйте ещё раз.")
        continue  # переходим к следующей итерации цикла, не прерывая программу

    if num == 0:
        break  # 0 — сигнал остановки, выходим из цикла

    total += num  # добавляем число к сумме

print(f"Сумма всех введённых чисел: {total}")