n = 5

# Факториал: накапливаем произведение в переменной result
result = 1
for i in range(1, n + 1):
    result *= i

print(f"{n}! = {result}")

# Таблица умножения от 1 до 5:
# внешний цикл выбирает множитель i (строку),
# вложенный перебирает множитель j (столбец)
print("\nТаблица умножения:")
for i in range(1, 6):
    row = ""
    for j in range(1, 6):
        row += f"{i * j:4}"
    print(row)