# Заданное число в списке
numbers = [4, 8, 15, 16, 23, 42]
target = 23

for number in numbers:
    if number == target:
        print("Нашли")
        break
else:
    # else у цикла выполняется только если цикл завершился штатно,
    # то есть перебрал все элементы и ни разу не был прерван через break.
    # Здесь он сработает, когда target не найден в списке.
    print("Не нашли")